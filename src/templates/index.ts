export const templates: Template[] = seeds.map(
  ([name, category, tagline, accent, paper], i) => ({
    id: `builtin-${i}`,
    name,
    category,
    tagline,
    accent,
    paper,
    pattern: i % 6,
    layout: {
      font: i % 4 === 0 ? "Noto Sans Arabic" : "Noto Naskh Arabic",
      size: i % 3 === 0 ? 17 : 16,
      line: 1.7 + (i % 4) * 0.15,
      top: 18 + (i % 5) * 2,
      bottom: 20 + (i % 3) * 2,
      inside: 19 + (i % 4),
      outside: 16 + (i % 5),
      align: category === "Poetry" ? "center" : "justify",
      color: accent,
      background: paper,
      spacing: 6 + (i % 5),
      indent: category === "Literature" ? 5 : 0,
    },
  }),
);
export function newBook(input: Partial<Book>, t: Template): Book {
  const chapter = uid(),
    now = Date.now();
  return {
    version: 1,
    id: uid(),
    title: "نوی کتاب",
    subtitle: "",
    author: "",
    publisher: "",
    description: "",
    language: "ps",
    genre: t.category,
    year: String(new Date().getFullYear()),
    templateId: t.id,
    layout: { ...defaultLayout, ...t.layout },
    chapters: [
      {
        id: chapter,
        title: input.language === "en" ? "Chapter 1" : "لومړی څپرکی",
        matter: "main",
        start: "next",
      },
    ],
    pages: [{ id: uid(), chapterId: chapter, html: "<p></p>", layout: {} }],
    cover: makeCover(input.title || "نوی کتاب", input.author || "", t.accent),
    created: now,
    updated: now,
    folder: "",
    ...input,
  };
}
